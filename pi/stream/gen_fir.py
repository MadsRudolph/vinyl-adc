#!/usr/bin/env python3
"""Write fir_taps.h from decimate.compensating_fir(), so the C streamer uses the ripper's exact filter."""
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent.parent))
import decimate as d
h=d.compensating_fir()
out=Path(__file__).with_name('fir_taps.h')
out.write_text('/* Generated by stream/gen_fir.py from decimate.compensating_fir(): do not edit. */\n'
               f'#define FIR_TAPS {len(h)}\nstatic const double fir_h[FIR_TAPS]={{\n'+',\n'.join(repr(float(v)) for v in h)+'\n};\n')
print(f'{out}: {len(h)} taps')
